export const scoringRubric = '0: no relevant Japanese response; 1: fragmentary meaning, major errors; 2: partly fulfills the task with recurring form/register errors; 3: fulfills the task with minor errors; 4: fulfills all requested information with accurate particles, natural expressions and appropriate register. Equivalent valid answers are accepted; reference is illustrative only.';

export const studyBank: Question[] = (Object.keys(rows) as Form[]).flatMap(form => {
  const r = rows[form];
  const make = (dimension: Question['dimension'], kind: Question['kind'], prompt: string, answer: string, i: number, options?: string[]): Question => ({
    id: `${form}-${dimension}-${i + 1}`, form, dimension, kind, prompt, options,
    answers: [answer], reference: answer, rubric: kind === 'writing' ? scoringRubric : 'Exact answer after Unicode normalization. Recall variants may be accepted by human review.', source: 'authored'
  });
  return [
    ...r.recognition.map(([p, o, a], i) => make('vocabularyRecognition', 'choice', p, a, i, o)),
    ...r.recall.map(([p, a], i) => make('vocabularyRecall', 'recall', p, a, i)),
    ...r.context.map(([p, a], i) => make('contextualUsage', 'writing', p, a, i)),
    ...r.conversation.map(([p, a], i) => make('conversation', 'writing', p, a, i)),
    ...r.grammar.map(([p, o, a], i) => make('grammar', 'choice', p, a, i, o))
  ];
});

